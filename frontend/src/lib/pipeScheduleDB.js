/**
 * Given NPS + Schedule → return { od_mm, wall_mm, weight_per_meter_kg } or null.
 * @param {string} nps  e.g. "8" or "8\""
 * @param {string} sch  e.g. "40" or "SCH 40"
 * @param {number} density_kg_m3  default 7850 for carbon steel
 */
export function lookupPipeSchedule(nps, sch, density_kg_m3 = 7850) {
  if (!nps || !sch) return null;
  const cleanNps = String(nps).replace(/"/g, "").replace(/\s+/g, "").replace("SCH", "").replace("sch", "");
  const cleanSch = String(sch).toUpperCase().replace("SCH", "").replace(/\s+/g, "");
  const od = PIPE_NPS_TO_OD_MM[cleanNps];
  const row = PIPE_SCH_WALL_MM[cleanNps];
  if (!od || !row) return null;
  const wall = row[cleanSch];
  if (!wall) return null;
  // Weight per meter (kg/m) = π × (OD − t) × t × ρ / 1e6
  const wpm = Math.PI * (od - wall) * wall * density_kg_m3 / 1e6;
  return { od_mm: od, wall_mm: wall, weight_per_meter_kg: Math.round(wpm * 1000) / 1000 };
}

